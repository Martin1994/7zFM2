using System.Globalization;
using System.Text;
using System.Xml;
using System.Xml.Linq;

namespace SevenZip.FileManager2.IconGenerator;

/// <summary>Shared tile, palette, metadata and deterministic, culture-independent SVG serialization.</summary>
public static class SvgDocument
{
  public static readonly XNamespace Namespace = "http://www.w3.org/2000/svg";

    public static string Number(double value)
    {
        return Math.Round(value, 4, MidpointRounding.AwayFromZero).ToString("0.####", CultureInfo.InvariantCulture);
    }

    public static XElement Rectangle(double x, double y, double width, double height, string role)
    {
      return new XElement(Namespace + "rect",
        new XAttribute("x", Number(x)), new XAttribute("y", Number(y)),
        new XAttribute("width", Number(width)), new XAttribute("height", Number(height)),
        new XAttribute("data-role", role));
    }

    public static string Create(IconStyle style, string title, string description, string source, params XElement[] body)
    {
        style.Validate();
        string size = Number(style.Size);
        string radius = Number(style.CornerRadius);
      var tile = new XElement(Namespace + "rect",
        new XAttribute("width", size), new XAttribute("height", size), new XAttribute("rx", radius));
      var background = new XElement(tile);
      background.SetAttributeValue("fill", style.Background);
      var document = new XDocument(
        new XElement(Namespace + "svg",
          new XAttribute("width", size), new XAttribute("height", size),
          new XAttribute("viewBox", $"0 0 {size} {size}"),
          new XAttribute("role", "img"), new XAttribute("aria-labelledby", "title desc"),
          new XElement(Namespace + "title", new XAttribute("id", "title"), title),
          new XElement(Namespace + "desc", new XAttribute("id", "desc"), description),
          new XComment(" Original concept artwork. SPDX-License-Identifier: MIT. Not an application resource. "),
          new XComment($" Generated by 7zFM2.IconGenerator from {source} and Shared/. Do not edit by hand. "),
          new XElement(Namespace + "defs",
            new XElement(Namespace + "clipPath", new XAttribute("id", "tile"), new XElement(tile))),
                background,
          new XElement(Namespace + "g", new XAttribute("clip-path", "url(#tile)"),
            new XAttribute("fill", style.Foreground), body)));

      var output = new StringBuilder();
      using (var writer = XmlWriter.Create(output, new XmlWriterSettings
      {
        OmitXmlDeclaration = true,
        Indent = true,
        NewLineChars = "\n",
        NewLineHandling = NewLineHandling.Entitize
      }))
      {
        document.Save(writer);
      }
      return output.ToString() + "\n";
    }
}